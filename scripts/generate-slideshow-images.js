const fs = require('fs');
const path = require('path');

const slideshowDir = path.join(__dirname, '..', 'public', 'images', 'slideshow');
const outputFile = path.join(slideshowDir, 'images.js');
const validExtensions = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp']);

const files = fs.readdirSync(slideshowDir)
  .filter(f => validExtensions.has(path.extname(f).toLowerCase()))
  .sort();

const content = `// Auto-generated by scripts/generate-slideshow-images.js — do not edit manually\nwindow.SLIDESHOW_IMAGES = ${JSON.stringify(files, null, 2)};\n`;

fs.writeFileSync(outputFile, content);
console.log(`Generated ${outputFile} with ${files.length} image(s).`);
